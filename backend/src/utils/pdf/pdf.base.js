const PDFDocument = require('pdfkit')

/**
 * Generate PDF buffer for Report Cards, Receipts, Payslips, Challans
 */
const FOOTER_PAGES = Symbol('footerPages')

/** Runs fn with the bottom margin removed, so footer text below it doesn't spawn a new page. */
const withoutBottomMargin = (doc, fn) => {
  const margin = doc.page.margins.bottom
  doc.page.margins.bottom = 0
  try {
    fn()
  } finally {
    doc.page.margins.bottom = margin
  }
}

/**
 * Pages are buffered so the real page count is known at the end: every page that got a
 * footer is stamped "Page i of n" (LOW-02: it used to say "Page 1" on every page).
 */
const stampPageNumbers = (doc) => {
  const footerPages = doc[FOOTER_PAGES]
  if (!footerPages || footerPages.size === 0) return
  const { start, count } = doc.bufferedPageRange()
  for (let i = start; i < start + count; i++) {
    if (!footerPages.has(i)) continue
    doc.switchToPage(i)
    const contentWidth = Math.floor(doc.page.width - 80) || 515
    const bottomY = Math.floor(doc.page.height - 50) || 770
    withoutBottomMargin(doc, () => {
      doc.fontSize(8).font('Helvetica').fillColor('#6B7280')
        .text(`Page ${i - start + 1} of ${count}`, 40 + contentWidth - 80, bottomY + 8, { align: 'right', width: 80, lineBreak: false })
    })
  }
}

const generatePDFBuffer = (pdfBuilderFn, docOptions = { margin: 40, size: 'A4' }) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ ...docOptions, bufferPages: true })
      const buffers = []

      doc.on('data', chunk => buffers.push(chunk))
      doc.on('end', () => resolve(Buffer.concat(buffers)))
      doc.on('error', err => reject(err))

      pdfBuilderFn(doc)
      stampPageNumbers(doc)
      doc.end()
    } catch (err) {
      reject(err)
    }
  })
}

const drawHeader = (doc, title, subtitle, branding = {}) => {
  const schoolName = (branding && branding.schoolName) || 'SCHOOL MANAGEMENT SYSTEM'
  const primaryColor = (branding && branding.primaryColor) || '#3730A3'
  const schoolTagline = (branding && branding.schoolTagline) || ''
  const contentWidth = Math.floor(doc.page.width - 80) || 515

  // Brand color banner box
  doc.rect(40, 40, contentWidth, 60).fill(primaryColor)

  doc.fillColor('#FFFFFF')
    .fontSize(16)
    .font('Helvetica-Bold')
    .text(schoolName.toUpperCase(), 40, 48, { align: 'center', width: contentWidth })

  if (schoolTagline) {
    doc.fontSize(8)
      .font('Helvetica-Oblique')
      .text(schoolTagline, 40, 64, { align: 'center', width: contentWidth })
    doc.fontSize(10)
      .font('Helvetica')
      .text(title.toUpperCase(), 40, 75, { align: 'center', width: contentWidth })
  } else {
    doc.fontSize(11)
      .font('Helvetica')
      .text(title.toUpperCase(), 40, 68, { align: 'center', width: contentWidth })
  }

  if (subtitle) {
    doc.fontSize(8)
      .font('Helvetica')
      .text(subtitle, 40, 85, { align: 'center', width: contentWidth })
  }

  doc.fillColor('#000000').moveDown(3)
}

const drawFooter = (doc, title) => {
  const contentWidth = Math.floor(doc.page.width - 80) || 515
  const bottomY = Math.floor(doc.page.height - 50) || 770
  doc.moveTo(40, bottomY).lineTo(40 + contentWidth, bottomY).strokeColor('#E5E7EB').stroke()

  withoutBottomMargin(doc, () => {
    doc.fontSize(8)
      .font('Helvetica')
      .fillColor('#6B7280')
      .text(`Generated by SMS Portal v1.0 • ${new Date().toLocaleString()}`, 40, bottomY + 8, { align: 'left', width: contentWidth - 100, lineBreak: false })
  })
  doc.fillColor('#000000')

  // The page number is stamped by generatePDFBuffer once the total page count is known
  if (typeof doc.bufferedPageRange === 'function') {
    const { start, count } = doc.bufferedPageRange()
    if (!doc[FOOTER_PAGES]) doc[FOOTER_PAGES] = new Set()
    doc[FOOTER_PAGES].add(start + count - 1)
  }
}

module.exports = {
  generatePDFBuffer,
  stampPageNumbers,
  drawHeader,
  drawFooter,
}
